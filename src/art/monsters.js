/** Um quadro do Cativo como matriz 32×32 de cores, já com contorno escuro. */
export function monsterFrame(key, u) {
  const { grid: a, rect, ellipse } = createPixelGrid(32);
  MONSTER_SPRITES[key](rect, ellipse, u);
  return a.map((row, y) => row.map((c, x) => c || (OUTLINE_DIRS.some(([dx, dy]) => a[y + dy] && a[y + dy][x + dx] && a[y + dy][x + dx] !== MC.dk) ? MC.dk : null)));
}

const CACHE = {};
/** Folha de sprite 64×32 (dois quadros lado a lado) como data URL. */
export function monsterArt(key) {
  if (CACHE[key]) return CACHE[key];
  const c = document.createElement('canvas');
  c.width = 64; c.height = 32;
  const ctx = c.getContext('2d');
  [0, 1].forEach(u => monsterFrame(key, u).forEach((row, y) => row.forEach((col, x) => {
    if (col) { ctx.fillStyle = col; ctx.fillRect(u * 32 + x, y, 1, 1); }
  })));
  return CACHE[key] = c.toDataURL();
}
